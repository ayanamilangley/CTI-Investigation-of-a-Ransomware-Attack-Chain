import csv
import json
import zipfile
from collections import Counter
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
DATA = BASE.parent / "week05" / "data"
RESULTS = BASE / "results"

SYSMON = "microsoft-windows-sysmon/operational"
CAR_DLLS = ("dbghelp.dll", "dbgcore.dll")

W5_ACCESS = {"0x1fffff", "0x1010", "0x1410", "0x143a", "0x1438"}
W5_NORMAL = {"msmpeng.exe", "svchost.exe", "wmiprvse.exe", "csrss.exe", "wininit.exe",
             "services.exe", "lsm.exe", "mrt.exe", "vmtoolsd.exe", "taskmgr.exe"}


def exe(path):
    return str(path or "").split("\\")[-1].lower()


def load_events():
    events = []
    for z in sorted(DATA.glob("*.zip")):
        with zipfile.ZipFile(z) as zf:
            for name in zf.namelist():
                if not name.endswith(".json"):
                    continue
                for line in zf.open(name):
                    r = json.loads(line)
                    r["_dataset"] = z.stem
                    events.append(r)
    return events


def is_lsass_access(r):
    return (str(r.get("Channel", "")).lower() == SYSMON and r.get("EventID") == 10
            and exe(r.get("TargetImage")) == "lsass.exe")


def car_2020_05_001(r):
    """The CAR analytic: lsass access whose call trace has dbghelp.dll or dbgcore.dll."""
    trace = str(r.get("CallTrace", "")).lower()
    return [d for d in CAR_DLLS if d in trace]


def week5_filter(r):
    """Our Week 5 H3 logic: strong access mask from a process that is not on the allowlist."""
    return (exe(r.get("SourceImage")) not in W5_NORMAL
            and str(r.get("GrantedAccess", "")).lower() in W5_ACCESS)


def main():
    events = load_events()
    lsass = [r for r in events if is_lsass_access(r)]
    total = Counter(r["_dataset"] for r in events)
    n_lsass = Counter(r["_dataset"] for r in lsass)

    rows, compare = [], []
    car_hits, w5_hits = Counter(), Counter()
    for r in lsass:
        dlls = car_2020_05_001(r)
        w5 = week5_filter(r)
        if dlls:
            car_hits[r["_dataset"]] += 1
        if w5:
            w5_hits[r["_dataset"]] += 1
        row = {
            "dataset": r["_dataset"],
            "host": str(r.get("Hostname", "")).split(".")[0].upper(),
            "time_utc": str(r.get("UtcTime", ""))[:19],
            "source_process": exe(r.get("SourceImage")),
            "source_pid": r.get("SourceProcessId", ""),
            "granted_access": r.get("GrantedAccess", ""),
            "car_hit": "yes" if dlls else "no",
            "matched_dll": ", ".join(dlls),
            "week5_hit": "yes" if w5 else "no",
            "call_trace": str(r.get("CallTrace", "")),
        }
        if dlls:
            rows.append(row)
        if dlls or w5:
            compare.append(row)

    RESULTS.mkdir(exist_ok=True)
    fields = ["dataset", "host", "time_utc", "source_process", "source_pid",
              "granted_access", "matched_dll", "call_trace"]
    with open(RESULTS / "car_results.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for row in rows:
            w.writerow({k: row[k] for k in fields})

    md = ["# CAR-2020-05-001 results (generated by scripts/car_analytic.py)", "",
          f"Events scanned: **{len(events)}** | LSASS access events (Sysmon 10): **{len(lsass)}** | "
          f"CAR analytic hits: **{sum(car_hits.values())}** | Week 5 filter hits: **{sum(w5_hits.values())}**", "",
          "| Dataset | All events | LSASS access (Sysmon 10) | CAR-2020-05-001 hits | Week 5 filter hits |",
          "|---|---|---|---|---|"]
    for d in sorted(total):
        md.append(f"| {d} | {total[d]} | {n_lsass[d]} | {car_hits[d]} | {w5_hits[d]} |")
    md += ["", "Events found by at least one of the two methods:", "",
           "| Host | Time (UTC) | Source process | GrantedAccess | CAR analytic | Week 5 filter | DLL in CallTrace |",
           "|---|---|---|---|---|---|---|"]
    for r in compare:
        md.append(f"| {r['host']} | {r['time_utc']} | `{r['source_process']}` | {r['granted_access']} | "
                  f"{r['car_hit']} | {r['week5_hit']} | {r['matched_dll'] or '-'} |")
    (RESULTS / "car_results.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    print(f"Scanned {len(events)} events, {len(lsass)} LSASS accesses")
    print(f"CAR-2020-05-001 hits: {sum(car_hits.values())}  |  Week 5 filter hits: {sum(w5_hits.values())}")
    print("Wrote results/car_results.csv and results/car_results.md")


if __name__ == "__main__":
    main()
